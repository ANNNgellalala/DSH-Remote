<#
.SYNOPSIS
  Build a signed Release APK for DshRemote (arm64-v8a, APK format).

.DESCRIPTION
  Wraps `dotnet publish` with the properties this machine needs and signs the
  APK with the keystore generated by scripts/gen-signing-key.ps1. The csproj is
  never modified: every setting is passed as a -p: property.

  Build shape (M4):
    - Configuration Release, net10.0-android
    - AndroidPackageFormats=apk (no AAB)
    - RuntimeIdentifier=android-arm64 (only arm64-v8a)
    - AndroidLinkMode=SdkOnly (framework assemblies linked, app/UI assemblies kept)
    - AndroidKeyStore=true + AndroidSigning* for the local release keystore

  The signed APK is copied to dist/apk/ and verified with apksigner when the
  Android build-tools provide it. Passwords come from -StorePass/-KeyPass or the
  DSHREMOTE_KEYSTORE_PASS / DSHREMOTE_KEY_PASS environment variables.

.PARAMETER OutputDir
  Where to copy the final APK (default: <repo>/dist/apk).

.PARAMETER DisplayVersion
  Override ApplicationDisplayVersion (default: csproj value).

.PARAMETER VersionCode
  Override ApplicationVersion (default: csproj value).

.PARAMETER LinkMode
  AndroidLinkMode override (default: SdkOnly). Use None if the trimmed build
  crashes at startup, Medium/Full are NOT validated by this project.

.PARAMETER NoSignVerify
  Skip the apksigner verification step.

.EXAMPLE
  pwsh -File scripts/build-release-apk.ps1

.EXAMPLE
  $env:DSHREMOTE_KEYSTORE_PASS = '...'; pwsh -File scripts/build-release-apk.ps1 -DisplayVersion 0.2.0 -VersionCode 2
#>
[CmdletBinding()]
param(
  [string]$OutputDir,
  [string]$KeystorePath,
  [string]$Alias = 'dshremote',
  [string]$StorePass = $env:DSHREMOTE_KEYSTORE_PASS,
  [string]$KeyPass = $env:DSHREMOTE_KEY_PASS,
  [string]$DisplayVersion,
  [string]$VersionCode,
  [ValidateSet('None', 'SdkOnly', 'Full')]
  [string]$LinkMode = 'SdkOnly',
  [string]$AndroidSdkDirectory = $env:DSHREMOTE_ANDROID_SDK,
  [string]$JavaSdkDirectory = $env:JAVA_HOME,
  [switch]$NoSignVerify,
  # Standard release flow: upload the signed APK to the VPS resource centre and verify the read-back sha256.
  [switch]$Publish,
  [switch]$NoKeepVersions
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
. (Join-Path $PSScriptRoot 'android-env.ps1')
if (-not $OutputDir) { $OutputDir = Join-Path $repoRoot 'dist\apk' }
if (-not $KeystorePath) { $KeystorePath = Join-Path $repoRoot 'app\keys\release.keystore' }

$project = Join-Path $repoRoot 'app/src/DshRemote.App.Android/DshRemote.App.Android.csproj'
if (-not (Test-Path -LiteralPath $project)) { throw "Android project not found: $project" }
if (-not (Test-Path -LiteralPath $KeystorePath)) {
  throw "Release keystore not found: $KeystorePath. Run `pwsh -File scripts/gen-signing-key.ps1` first."
}
if (-not $StorePass) { throw 'Missing store password: pass -StorePass or set DSHREMOTE_KEYSTORE_PASS.' }
if (-not $KeyPass) { $KeyPass = $StorePass }

$toolchain = Resolve-AndroidToolchain -AndroidSdkDirectory $AndroidSdkDirectory -JavaSdkDirectory $JavaSdkDirectory
$keystoreFull = (Resolve-Path -LiteralPath $KeystorePath).Path

# A stale incremental Release output can produce an APK whose libxamarin-app.so assembly store is
# incomplete, which crashes at startup with UnsatisfiedLinkError n_onCreate. Always rebuild the
# Android Release outputs from scratch so every shipped APK carries a complete managed assembly store.
$androidProjectDir = Split-Path -Parent $project
foreach ($stale in @(
    (Join-Path $androidProjectDir 'bin/Release'),
    (Join-Path $androidProjectDir 'obj/Release'))) {
  if (Test-Path -LiteralPath $stale) {
    Write-Host "  clean   : $stale"
    Remove-Item -LiteralPath $stale -Recurse -Force
  }
}

$artifactsDir = Join-Path $repoRoot 'app/src/DshRemote.App.Android/bin/Release/net10.0-android'
Write-Host 'Release APK build' -ForegroundColor Cyan
Write-Host "  project : $project"
Write-Host "  SDK     : $($toolchain.Sdk)"
Write-Host "  JDK     : $($toolchain.Jdk)"
Write-Host "  keystore: $keystoreFull (alias: $Alias)"
Write-Host "  link    : $LinkMode, RID android-arm64, APK format"
if ($DisplayVersion) { Write-Host "  version : $DisplayVersion ($($VersionCode ?? 'unchanged'))" }

$arguments = @(
  'publish', $project,
  '-c', 'Release',
  '-f', 'net10.0-android',
  "-p:AndroidSdkDirectory=$($toolchain.Sdk)",
  "-p:JavaSdkDirectory=$($toolchain.Jdk)",
  '-p:AndroidPackageFormats=apk',
  '-p:RuntimeIdentifier=android-arm64',
  "-p:AndroidLinkMode=$LinkMode",
  '-p:AndroidKeyStore=true',
  "-p:AndroidSigningKeyStore=$keystoreFull",
  "-p:AndroidSigningKeyAlias=$Alias",
  "-p:AndroidSigningStorePass=$StorePass",
  "-p:AndroidSigningKeyPass=$KeyPass"
)
if ($DisplayVersion) { $arguments += "-p:ApplicationDisplayVersion=$DisplayVersion" }
if ($VersionCode) { $arguments += "-p:ApplicationVersion=$VersionCode" }
# The settings page shows the app version from the entry assembly's informational version, which is not
# derived from ApplicationDisplayVersion — pass it explicitly so the About section matches the APK.
if ($DisplayVersion) { $arguments += "-p:Version=$DisplayVersion" }

# Passwords must not leak into the console/log: build output is captured, and
# only the failing tail is printed.
$buildLog = Join-Path ([System.IO.Path]::GetTempPath()) ("dsh-release-build-" + [guid]::NewGuid().ToString('N') + '.log')
try {
  & dotnet @arguments *> $buildLog
  $buildExit = $LASTEXITCODE
  if ($buildExit -ne 0) {
    $tail = Get-Content -LiteralPath $buildLog -Tail 60
    Write-Host '--- dotnet publish (tail) ---' -ForegroundColor Red
    $tail | ForEach-Object { Write-Host $_ }
    throw "dotnet publish failed with exit code $buildExit (full log: $buildLog)"
  }
} finally {
  if ($buildExit -eq 0) { Remove-Item -LiteralPath $buildLog -Force -ErrorAction SilentlyContinue }
}

$apk = Get-ChildItem -LiteralPath $artifactsDir -Recurse -Filter '*-Signed.apk' -File -ErrorAction SilentlyContinue |
  Sort-Object LastWriteTime -Descending | Select-Object -First 1
if (-not $apk) { throw "Publish succeeded but no *-Signed.apk found under $artifactsDir" }

if (-not (Test-Path -LiteralPath $OutputDir)) { New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null }
$versionLabel = if ($DisplayVersion) { $DisplayVersion } else { 'release' }
$codeLabel = if ($VersionCode) { "-$VersionCode" } else { '' }
$target = Join-Path $OutputDir "dshremote-$versionLabel$codeLabel-arm64-release.apk"
Copy-Item -LiteralPath $apk.FullName -Destination $target -Force
$targetItem = Get-Item -LiteralPath $target
$sizeMb = [math]::Round($targetItem.Length / 1MB, 2)
$sha = (Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash.ToLowerInvariant()

# Verify the signature with apksigner when available.
$signerInfo = $null
if (-not $NoSignVerify -and $toolchain.ApkSigner) {
  $verifyLog = Join-Path ([System.IO.Path]::GetTempPath()) ("dsh-apksigner-" + [guid]::NewGuid().ToString('N') + '.log')
  try {
    & $toolchain.ApkSigner verify --print-certs $target *> $verifyLog
    if ($LASTEXITCODE -ne 0) {
      $tail = Get-Content -LiteralPath $verifyLog -Tail 20
      throw "apksigner verify failed:`n$($tail -join "`n")"
    }
    $signerInfo = Get-Content -LiteralPath $verifyLog | Where-Object { $_ -match 'certificate DN|SHA-256 digest' } | Select-Object -First 2
  } finally {
    Remove-Item -LiteralPath $verifyLog -Force -ErrorAction SilentlyContinue
  }
}

Write-Host ''
Write-Host 'Release APK:' -ForegroundColor Green
Write-Host "  path   : $target"
Write-Host "  size   : $sizeMb MB ($($targetItem.Length) bytes)"
Write-Host "  sha256 : $sha"
Write-Host "  signer : $(if ($signerInfo) { ($signerInfo -join ' | ') } else { 'not verified' })"
if ($sizeMb -gt 40) {
  Write-Warning "APK is larger than the 40 MB budget ($sizeMb MB). Check LinkMode/ABIs/embedded assemblies (requested link mode: $LinkMode)."
} elseif ($sizeMb -gt 30) {
  Write-Warning "APK is above the ~20-30 MB target ($sizeMb MB)."
} else {
  Write-Host '  size   : within the ~20-30 MB target' -ForegroundColor Green
}
Write-Host ''
Write-Host "Install: adb install -r -t `"$target`""

# Standard release flow: publish to the VPS resource centre right after the signed
# artifact is produced. scripts/release-apk.ps1 wraps this for one-command releases.
if ($Publish) {
  Write-Host ''
  Write-Host 'Publishing to the VPS resource centre...' -ForegroundColor Cyan
  $sync = Join-Path $PSScriptRoot 'sync-apk.ps1'
  if (-not (Test-Path -LiteralPath $sync)) { throw "publish script not found: $sync" }
  & $sync -File $target -Id dsh-remote -KeepVersions:(-not $NoKeepVersions)
  if ($LASTEXITCODE -ne 0) {
    # The gateway verification at the start of sync-apk.ps1 can race a tunnel
    # reconnect; one retry keeps the standard flow from failing a good build.
    Write-Warning "APK upload failed (exit $LASTEXITCODE); retrying once in 5s..."
    Start-Sleep -Seconds 5
    & $sync -File $target -Id dsh-remote -KeepVersions:(-not $NoKeepVersions)
  }
  if ($LASTEXITCODE -ne 0) { throw "APK upload failed (sync-apk exit code $LASTEXITCODE)" }
} else {
  Write-Warning 'This build was NOT published. Releases must go through scripts/release-apk.ps1 (or add -Publish).'
}


